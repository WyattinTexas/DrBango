const SS_LANG = (() => {
  const qs = new URLSearchParams(location.search);
  const q = (qs.get('lang') || '').toLowerCase();
  if (SS_STR[q]) { try { localStorage.setItem('beta3.lang', q); } catch (e) { } return q; }
  let saved = null;
  try { saved = localStorage.getItem('beta3.lang'); } catch (e) { }
  if (SS_STR[saved]) return saved;
  // a saved pref naming a language that no longer ships (the v0.71.0 cut to
  // five) is cleared, and the pick falls through to the device locale below —
  // the player lands in their locale's best of the five, else English.
  if (saved) { try { localStorage.removeItem('beta3.lang'); } catch (e) { } }
  const nav = ((navigator.language || 'en').slice(0, 2)).toLowerCase();
  return SS_STR[nav] ? nav : 'en';
})();

function SS_T(key) {
  let s = (SS_STR[SS_LANG] && SS_STR[SS_LANG][key]) || SS_STR.en[key] || key;
  for (let i = 1; i < arguments.length; i++) s = s.replace('%' + i, arguments[i]);
  return s;
}

// Localized name/desc for a sigil def, at a TIER of its ladder (v0.66.0;
// default 1 keeps every pre-tier call site exact). English lives in data.js
// (the canonical copy); other languages carry a `sig` map of id →
// [name, desc] — grown to [name, descI, descII, …] where a tier changes the
// WORDS — and fall back per-sigil so a partial map ships gracefully (the
// index clamps, so an untranslated ladder shows its base desc). Template
// descs carry %1..%k, substituted from the def fields `dvf` names at the
// tier's own values (ssSigilField walks 'lb.add' paths) — the text is
// GENERATED from the numbers, so desc and effect can never drift.
function SS_SIG(s, tier) {
  const t = Math.max(1, Math.min((tier | 0) || 1, 1 + ((s.tl || []).length)));
  const m = (SS_STR[SS_LANG] && SS_STR[SS_LANG].sig) || {};
  const e = m[s.id];
  let desc = e ? e[Math.min(t, e.length - 1)] : ((t >= 2 && s.tl[t - 2].desc) || s.desc);
  if (s.dvf) for (let i = 0; i < s.dvf.length; i++) desc = desc.replace('%' + (i + 1), ssSigilField(s, s.dvf[i], t));
  return { name: e ? e[0] : s.name, desc };
}

/* The sentence that unlocks a locked sigil, localized. English is canonical in
   data.js (`lock.how`, %1 = the target) so the condition and its number can
   never drift apart; other languages carry an `unl` map of id → sentence and
   fall back per-sigil, so a partial translation ships gracefully. Returns ''
   for a sigil that was never locked. */
function SS_SIG_HOW(s) {
  if (!s || !s.lock) return '';
  const m = (SS_STR[SS_LANG] && SS_STR[SS_LANG].unl) || {};
  return String(m[s.id] || s.lock.how || '').replace('%1', s.lock.n);
}

