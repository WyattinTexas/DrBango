const SS_LANG = (() => {
  const qs = new URLSearchParams(location.search);
  const q = (qs.get('lang') || '').toLowerCase();
  if (SS_STR[q]) { try { localStorage.setItem('beta3.lang', q); } catch (e) { } return q; }
  let saved = null;
  try { saved = localStorage.getItem('beta3.lang'); } catch (e) { }
  if (SS_STR[saved]) return saved;
  const nav = ((navigator.language || 'en').slice(0, 2)).toLowerCase();
  return SS_STR[nav] ? nav : 'en';
})();

function SS_T(key) {
  let s = (SS_STR[SS_LANG] && SS_STR[SS_LANG][key]) || SS_STR.en[key] || key;
  for (let i = 1; i < arguments.length; i++) s = s.replace('%' + i, arguments[i]);
  return s;
}

// Localized name/desc for a sigil def. English lives in data.js (the canonical
// copy); other languages carry a `sig` map of id → [name, desc] and fall back
// per-sigil so a partial map ships gracefully.
function SS_SIG(s) {
  const m = (SS_STR[SS_LANG] && SS_STR[SS_LANG].sig) || {};
  const t = m[s.id];
  return t ? { name: t[0], desc: t[1] } : { name: s.name, desc: s.desc };
}

/* The sentence that unlocks a locked sigil, localized. English is canonical in
   data.js (`lock.how`, %1 = the target) so the condition and its number can
   never drift apart; other languages carry an `unl` map of id → sentence and
   fall back per-sigil, so a partial translation ships gracefully. Returns ''
   for a sigil that was never locked. */
function SS_SIG_HOW(s) {
  if (!s || !s.lock) return '';
  const m = (SS_STR[SS_LANG] && SS_STR[SS_LANG].unl) || {};
  return String(m[s.id] || s.lock.how || '').replace('%1', s.lock.n);
}

// Localized flavor title for a beast. English lives in data.js (the canonical
// copy); other languages carry a `beast` map of id → title with per-beast
// fallback. Latin constellation NAMES (VULPES, ORION…) are never translated.
function SS_BEAST_T(b) {
  const m = (SS_STR[SS_LANG] && SS_STR[SS_LANG].beast) || {};
  return m[b.id] || b.title;
}

