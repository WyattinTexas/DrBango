// Localized title/desc for a zodiac sign, at a LEVEL of its ladder
// (v0.69.0; default 1 keeps every pre-level call site exact — SS_SIG's own
// law). English lives in data.js (the canonical copy); other languages
// carry a `zod` map of id → [title, desc] — grown to [title, desc0,
// desc1, …] where a level advances the WORDING (`db` on the def lists the
// crossing levels; the index clamps, so a partial translation shows its
// base desc) — with per-sign fallback. Template descs carry %1..%k,
// substituted from the def fields `dvf` names at the level's own values
// (ssSignVal) — the text is GENERATED from the numbers, so desc and
// effect can never drift. Latin sign NAMES (ARIES, LIBRA…) never
// translate.
function SS_ZOD(z, lv) {
  const L = Math.max(1, (lv | 0) || 1);
  const m = (SS_STR[SS_LANG] && SS_STR[SS_LANG].zod) || {};
  const t = m[z.id];
  const band = (z.db || []).filter((b) => b <= L).length;
  let desc;
  if (t) desc = t[Math.min(1 + band, t.length - 1)];
  else desc = band > 0 && z.dvs ? z.dvs[Math.min(band - 1, z.dvs.length - 1)] : z.desc;
  if (z.dvf) for (let i = 0; i < z.dvf.length; i++) desc = desc.replace('%' + (i + 1), ssSignVal(z.id, z.dvf[i], L));
  return { title: t ? t[0] : z.title, desc };
}

